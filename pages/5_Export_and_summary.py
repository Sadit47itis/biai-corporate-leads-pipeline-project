from io import BytesIO

import pandas as pd
import streamlit as st
from openpyxl.styles import Font, PatternFill

import ai
import engine
import ui

flagged, issues, clean = ui.get_data()
st.session_state.setdefault("weekly_summary", None)


def build_xlsx() -> bytes:
    pipeline = flagged.copy()
    for c in pipeline.columns:  # Excel-friendly: dates as dates, no pandas NaT noise
        if pd.api.types.is_datetime64_any_dtype(pipeline[c]):
            pipeline[c] = pipeline[c].dt.date
    summary = engine.stage_summary(clean)
    sheets = {"Pipeline": pipeline, "Issues": issues, "Stage summary": summary}

    buf = BytesIO()
    with pd.ExcelWriter(buf, engine="openpyxl") as xw:
        for name, frame in sheets.items():
            frame.to_excel(xw, sheet_name=name, index=False)
            ws = xw.sheets[name]
            ws.freeze_panes = "A2"
            for cell in ws[1]:
                cell.font = Font(bold=True, color="FFFFFF")
                cell.fill = PatternFill("solid", fgColor=ui.PRIMARY.lstrip("#"))
            for col_cells in ws.columns:
                longest = max(len(str(c.value)) if c.value is not None else 0 for c in col_cells)
                ws.column_dimensions[col_cells[0].column_letter].width = min(max(10, longest + 2), 60)
    return buf.getvalue()

ui.render_header()

st.title("Export & weekly summary")

st.subheader("Excel export")
st.caption("Sheets: **Pipeline** (all 25 source rows plus flags), **Issues**, **Stage summary** "
           "(duplicates excluded). Source data is not changed.")
st.download_button("⬇ Download XLSX", build_xlsx(), file_name="corporate_leads_pipeline.xlsx",
                   mime="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
                   type="primary")

st.divider()
st.subheader("Weekly summary")
st.caption("Generated by the AI layer.")
if st.button("Generate weekly summary"):
    with st.spinner("Generating..."):
        st.session_state["weekly_summary"] = ai.weekly_summary(flagged)

if st.session_state["weekly_summary"]:
    with st.container(border=True):
        st.markdown(st.session_state["weekly_summary"])
    st.download_button("⬇ Download summary (.md)", st.session_state["weekly_summary"].encode("utf-8"),
                       file_name="weekly_summary.md", mime="text/markdown")
